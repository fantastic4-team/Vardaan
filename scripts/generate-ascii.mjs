// Turns public/images/tree.png into ASCII art for the landing page: lib/ascii-tree.ts.
// Each character cell samples the image; transparent cells become spaces, and brighter cells
// get denser characters (the page is dark, so bright = more ink).
// Run with `node scripts/generate-ascii.mjs [columns]`.
import { readFileSync, writeFileSync } from "fs";
import { inflateSync } from "zlib";

const COLS = Number(process.argv[2]) || 96;
// Monospace glyphs are roughly 0.6 as wide as they are tall.
const CHAR_ASPECT = 0.6;
const RAMP = " .,:;i1tfLCG08@";

// Minimal decoder for 8-bit RGBA, non-interlaced PNGs (which tree.png is).
function decodePng(buf) {
  const width = buf.readUInt32BE(16);
  const height = buf.readUInt32BE(20);
  if (buf[24] !== 8 || buf[25] !== 6 || buf[28] !== 0) throw new Error("expected 8-bit RGBA, non-interlaced PNG");
  const idat = [];
  for (let o = 8; o < buf.length; ) {
    const len = buf.readUInt32BE(o);
    const type = buf.toString("ascii", o + 4, o + 8);
    if (type === "IDAT") idat.push(buf.subarray(o + 8, o + 8 + len));
    o += 12 + len;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const bpp = 4;
  const stride = width * bpp;
  const out = Buffer.alloc(height * stride);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    for (let x = 0; x < stride; x++) {
      const v = raw[y * (stride + 1) + 1 + x];
      const a = x >= bpp ? out[y * stride + x - bpp] : 0;
      const b = y > 0 ? out[(y - 1) * stride + x] : 0;
      const c = x >= bpp && y > 0 ? out[(y - 1) * stride + x - bpp] : 0;
      let p;
      if (filter === 0) p = 0;
      else if (filter === 1) p = a;
      else if (filter === 2) p = b;
      else if (filter === 3) p = (a + b) >> 1;
      else {
        const pa = Math.abs(b - c);
        const pb = Math.abs(a - c);
        const pc = Math.abs(a + b - 2 * c);
        p = pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      out[y * stride + x] = (v + p) & 255;
    }
  }
  return { width, height, data: out };
}

const { width, height, data } = decodePng(readFileSync("public/images/tree.png"));
const cellW = width / COLS;
const cellH = cellW / CHAR_ASPECT;
const rows = Math.floor(height / cellH);

const lines = [];
for (let r = 0; r < rows; r++) {
  let line = "";
  for (let c = 0; c < COLS; c++) {
    // Average the cell.
    let lum = 0;
    let alpha = 0;
    let n = 0;
    for (let y = Math.floor(r * cellH); y < Math.floor((r + 1) * cellH); y += 2) {
      for (let x = Math.floor(c * cellW); x < Math.floor((c + 1) * cellW); x += 2) {
        const i = (y * width + x) * 4;
        const a = data[i + 3] / 255;
        lum += ((0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2]) / 255) * a;
        alpha += a;
        n++;
      }
    }
    alpha /= n;
    if (alpha < 0.35) {
      line += " ";
      continue;
    }
    const l = lum / Math.max(alpha * n, 1e-6);
    // Stretch the tree's mid-tones across the ramp and keep every visible cell at least a dot.
    const t = Math.min(1, Math.max(0, (l - 0.15) / 0.6));
    line += RAMP[1 + Math.round(t * (RAMP.length - 2))];
  }
  lines.push(line.replace(/\s+$/, ""));
}
while (lines.length && !lines[0].trim()) lines.shift();
while (lines.length && !lines[lines.length - 1].trim()) lines.pop();

writeFileSync(
  "lib/ascii-tree.ts",
  `// Generated by scripts/generate-ascii.mjs from public/images/tree.png. Do not edit by hand.\nexport const ASCII_TREE = ${JSON.stringify(lines.join("\n"))};\n\nexport const ASCII_TREE_COLS = ${COLS};\nexport const ASCII_TREE_ROWS = ${lines.length};\n`,
);
console.log(`wrote lib/ascii-tree.ts (${COLS} x ${lines.length})`);
console.log(lines.join("\n"));
